"""
Question:  Given two lists, merge them into a 
single new list without modifying the 
originals.
Hint: Use the + operator or a loop to 
combine. Example: list1 = [1, 2], list2 = [3, 4] → merged = [1, 2, 3, 4]
"""

# Solution

list1 = [1, 2]
list2 = [3, 4]

merged = list1 + list2
print(merged)  # [1, 2, 3, 4]